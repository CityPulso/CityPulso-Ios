#!/usr/bin/env python3
"""Fork the board game Swift code into every other Near activity type.

Android's activity stacks are copies of board game with the type renamed (PulsoNear-API/scripts/fork_activity.py); the
only differences are the generated DTOs, which already come from Android. iOS keeps the same rule: board game is
written by hand, every other type is generated from it here. Edit the board game file, then rerun.

  BoardGame → Mahjong / TexasHoldem …   (types)
  boardGame → mahjong / texasHoldem …   (identifiers)
  桌游       → 麻将 / 德州扑克 …          (comments, from the strings catalog)

Usage:
  python3 Scripts/fork_activity.py           # write
  python3 Scripts/fork_activity.py --check   # fail when a forked file differs from board game
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

IOS_ROOT = Path(__file__).resolve().parent.parent
NEAR = IOS_ROOT / "PulsoNear"

# Board game files every type gets a copy of (paths contain "BoardGame"), with the types (wire values) that do NOT take
# the copy. Mahjong carries its rule set (`mahjongVariant`), so its rows, create request and service glue (basic edit
# sends the rule set) are written by hand.
TEMPLATES: list[tuple[str, set[str]]] = [
    ("Data/BoardGame/BoardGameRepository.swift", set()),
    ("Events/BoardGameEventBus.swift", set()),
    ("Query/BoardGameQueryKeys.swift", set()),
    ("Query/BoardGameQueryStore.swift", set()),
    ("Services/BoardGameService.swift", set()),
    ("Services/BoardGameService+ActivityType.swift", {"mahjong"}),
    ("DI/Container+BoardGame.swift", set()),
    ("Features/Events/Rows/BoardGameRows.swift", {"mahjong"}),
    ("Features/Create/BoardGameCreate.swift", {"mahjong"}),
]

SOURCE = ("BoardGame", "boardGame", "board_game")


def kinds() -> list[tuple[str, str, str]]:
    """(Type, identifier, wire) for every Near activity type except board game, from the generated enum."""
    enum = (NEAR / "Enums/Generated/NearActivityKind.swift").read_text()
    body = enum[enum.index("enum NearActivityKind") :]
    out = []
    for case, wire in re.findall(r"^    case (\w+)(?: = \"(\w+)\")?$", body, re.M):
        wire = wire or case
        if wire == "board_game":
            continue
        out.append((case[0].upper() + case[1:], case, wire))
    return out


def zh_names() -> dict[str, str]:
    catalog = json.loads((NEAR / "Resources/Localizable.xcstrings").read_text())["strings"]
    names = {}
    for key, entry in catalog.items():
        if key.startswith("shell_home_module_"):
            unit = entry.get("localizations", {}).get("zh-Hans", {}).get("stringUnit")
            if unit:
                names[key.removeprefix("shell_home_module_")] = unit["value"]
    return names


def fork(text: str, kind: tuple[str, str, str], zh: dict[str, str]) -> str:
    type_name, identifier, wire = kind
    text = text.replace(SOURCE[0], type_name).replace(SOURCE[1], identifier).replace(SOURCE[2], wire)
    return text.replace(zh["board_game"], zh[wire])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when a forked file differs from board game")
    args = parser.parse_args()

    zh = zh_names()
    stale = []
    count = 0
    for template, skip in TEMPLATES:
        source = (NEAR / template).read_text()
        for kind in kinds():
            if kind[2] in skip:
                continue
            target = NEAR / fork(template, kind, zh)
            header = f"// Generated by Scripts/fork_activity.py from {template} — edit the board game file and rerun.\n\n"
            content = header + fork(source, kind, zh)
            count += 1
            if target.exists() and target.read_text() == content:
                continue
            stale.append(target)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    if args.check and stale:
        for path in stale:
            print(f"stale: {path.relative_to(IOS_ROOT)}", file=sys.stderr)
        print("run: python3 Scripts/fork_activity.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"{count} files ({len(stale)} written)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
