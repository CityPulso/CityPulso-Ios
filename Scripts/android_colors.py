#!/usr/bin/env python3
"""Generate the Swift Radix colour scales from CityPulso-Android `RadixColorScales.kt`.

Android (generated from @radix-ui/colors) is the source of truth. Each LIGHT / DARK pair becomes one `RadixScale` case
whose `step(n)` is a dynamic colour that follows the current appearance.

Usage:
  python3 Scripts/android_colors.py           # write
  python3 Scripts/android_colors.py --check   # fail when the Swift file differs from Android
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

IOS_ROOT = Path(__file__).resolve().parent.parent
SOURCE = IOS_ROOT.parent / "CityPulso-Android/pulsolink-ui/src/main/java/com/citypulso/pulsolink/ui/theme/color/RadixColorScales.kt"
OUTPUT = IOS_ROOT / "PulsoLinkUI/Sources/PulsoLinkUI/Theme/Generated/RadixScale.swift"


def render() -> str:
    text = SOURCE.read_text()
    scales: dict[str, dict[str, list[str]]] = {}
    for match in re.finditer(r"val (\w+)_(LIGHT|DARK) = RadixScale\((.*?)\n    \)", text, re.S):
        colors = [c[2:] for c in re.findall(r"Color\(0x([0-9A-Fa-f]{8})\)", match[3])]
        assert len(colors) == 12, match[1]
        scales.setdefault(match[1].lower(), {})[match[2].lower()] = colors
    names = list(scales)
    lines = [
        f"// Generated by Scripts/android_colors.py from {SOURCE.relative_to(IOS_ROOT.parent)} — do not edit.",
        "",
        "import SwiftUI",
        "import UIKit",
        "",
        "/** Radix 12 阶色阶（与 Android / WEB 同值）；`step(n)` 跟随深浅外观。 */",
        "public enum RadixScale: String, CaseIterable, Sendable {",
        *[f"    case {n}" for n in names],
        "",
        "    /** 第 [n] 阶（1…12）。 */",
        "    public func step(_ n: Int) -> Color {",
        "        let (light, dark) = (Self.light[self]![n - 1], Self.dark[self]![n - 1])",
        "        return Color(uiColor: UIColor { traits in",
        "            Self.uiColor(traits.userInterfaceStyle == .dark ? dark : light)",
        "        })",
        "    }",
        "",
        "    /** 固定用浅色档（地图针等不随外观变的地方）。 */",
        "    public func lightStep(_ n: Int) -> Color {",
        "        Color(uiColor: Self.uiColor(Self.light[self]![n - 1]))",
        "    }",
        "",
        "    private static func uiColor(_ argb: UInt32) -> UIColor {",
        "        UIColor(",
        "            red: CGFloat((argb >> 16) & 0xFF) / 255,",
        "            green: CGFloat((argb >> 8) & 0xFF) / 255,",
        "            blue: CGFloat(argb & 0xFF) / 255,",
        "            alpha: CGFloat((argb >> 24) & 0xFF) / 255",
        "        )",
        "    }",
        "",
    ]
    for mode in ("light", "dark"):
        lines.append(f"    private static let {mode}: [RadixScale: [UInt32]] = [")
        for n in names:
            values = ", ".join(f"0x{c.upper()}" for c in scales[n][mode])
            lines.append(f"        .{n}: [{values}],")
        lines += ["    ]", ""]
    lines[-1:] = ["}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if OUTPUT.exists() and OUTPUT.read_text() == content:
        return 0
    if args.check:
        print(f"stale: {OUTPUT.relative_to(IOS_ROOT)}\nrun: python3 Scripts/android_colors.py", file=sys.stderr)
        return 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"{OUTPUT.relative_to(IOS_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
