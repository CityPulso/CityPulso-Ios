#!/usr/bin/env python3
"""Fork the badminton Swift code into every other Loop sport.

Android's sport stacks are exact copies of badminton with the sport renamed (PulsoLoop-API/scripts/fork_sport.py); the
only differences are the generated DTOs, which already come from Android. iOS keeps the same rule: badminton is written
by hand, every other sport is generated from it here. Edit the badminton file, then rerun.

  Badminton → Tennis / TableTennis …   (types)
  badminton → tennis / tableTennis …   (identifiers)
  羽毛球     → 网球 / 乒乓球 …            (comments, from the strings catalog)

Usage:
  python3 Scripts/fork_sport.py           # write
  python3 Scripts/fork_sport.py --check   # fail when a forked file differs from badminton
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

IOS_ROOT = Path(__file__).resolve().parent.parent
LOOP = IOS_ROOT / "PulsoLoop"

# Badminton files that every sport gets a copy of (paths contain "Badminton").
TEMPLATES = [
    "Data/Badminton/BadmintonRepository.swift",
    "Events/BadmintonEventBus.swift",
    "Query/BadmintonQueryKeys.swift",
    "Query/BadmintonQueryStore.swift",
    "Services/BadmintonService.swift",
    "DI/Container+Badminton.swift",
]

SOURCE = ("Badminton", "badminton", "badminton")


def sports() -> list[tuple[str, str, str]]:
    """(Type, identifier, wire) for every Loop sport except badminton, from the generated LoopSport enum."""
    enum = (LOOP / "Enums/Generated/LoopSport.swift").read_text()
    body = enum[enum.index("enum LoopSport") :]
    out = []
    for case, wire in re.findall(r"^    case (\w+)(?: = \"(\w+)\")?$", body, re.M):
        wire = wire or case
        if wire == "badminton":
            continue
        out.append((case[0].upper() + case[1:], case, wire))
    return out


def zh_names() -> dict[str, str]:
    catalog = json.loads((LOOP / "Resources/Localizable.xcstrings").read_text())["strings"]
    names = {}
    for key, entry in catalog.items():
        if key.startswith("shell_home_module_"):
            unit = entry.get("localizations", {}).get("zh-Hans", {}).get("stringUnit")
            if unit:
                names[key.removeprefix("shell_home_module_")] = unit["value"]
    return names


def fork(text: str, sport: tuple[str, str, str], zh: dict[str, str]) -> str:
    type_name, identifier, wire = sport
    text = text.replace(SOURCE[0], type_name).replace(SOURCE[1], identifier)
    return text.replace(zh["badminton"], zh[wire])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when a forked file differs from badminton")
    args = parser.parse_args()

    zh = zh_names()
    stale = []
    count = 0
    for template in TEMPLATES:
        source = (LOOP / template).read_text()
        for sport in sports():
            target = LOOP / fork(template, sport, zh)
            header = f"// Generated by Scripts/fork_sport.py from {template} — edit the badminton file and rerun.\n\n"
            content = header + fork(source, sport, zh)
            count += 1
            if target.exists() and target.read_text() == content:
                continue
            stale.append(target)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    if args.check and stale:
        for path in stale:
            print(f"stale: {path.relative_to(IOS_ROOT)}", file=sys.stderr)
        print("run: python3 Scripts/fork_sport.py", file=sys.stderr)
        return 1
    if not args.check:
        print(f"{count} files for {len(sports())} sports ({len(stale)} written)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
