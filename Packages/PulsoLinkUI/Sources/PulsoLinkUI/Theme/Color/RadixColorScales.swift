/** 一个 Radix 色阶的 12 步。 */
public struct RadixScale: Sendable, Equatable {
    public let steps: [Color]

    init(_ hex: UInt32...) {
        precondition(hex.count == 12, "Radix scales have 12 steps")
        steps = hex.map(Color.init(rgb:))
    }

    /** 1-based，与 Radix `--{color}-{n}` 对应。 */
    public func step(_ n: Int) -> Color { steps[n - 1] }
}

extension Color {
    init(rgb: UInt32) {
        self.init(
            .sRGB,
            red: Double((rgb >> 16) & 0xFF) / 255,
            green: Double((rgb >> 8) & 0xFF) / 255,
            blue: Double(rgb & 0xFF) / 255,
            opacity: 1
        )
    }
}

